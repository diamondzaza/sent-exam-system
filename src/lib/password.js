/**
 * ─────────────────────────────────────────────────────────
 * ชื่อไฟล์: password.js
 * หน้าที่ของหน้านี้: ตรวจความแข็งแรงของรหัสผ่านตามนโยบายระบบ —
 *   ยาวอย่างน้อย 8 ตัวอักษร + มีตัวเลข + ตัวอักษรพิมพ์ใหญ่ + พิมพ์เล็ก + อักขระพิเศษ
 *   validatePassword คืนรายการข้อผิดพลาด (ว่าง = ผ่านทั้งหมด) ใช้ได้ทั้งฝั่ง client/server
 * ผู้ใช้งาน: AdminView (ฟอร์มผู้ใช้/อนุมัติบัญชี) + API routes
 * ─────────────────────────────────────────────────────────
 */
export function validatePassword(password) {
    const pw = password || '';
    const issues = [];
    if (pw.length < 8) issues.push('ยาวอย่างน้อย 8 ตัวอักษร');
    if (!/[0-9]/.test(pw)) issues.push('มีตัวเลข');
    if (!/[A-Z]/.test(pw)) issues.push('มีตัวอักษรพิมพ์ใหญ่');
    if (!/[a-z]/.test(pw)) issues.push('มีตัวอักษรพิมพ์เล็ก');
    if (!/[^A-Za-z0-9]/.test(pw)) issues.push('มีอักขระพิเศษ เช่น !@#$%');
    return issues;
}
